import nodemailer from "nodemailer";
import type SMTPTransport from "nodemailer/lib/smtp-transport";
import { renderEmail } from "../render";
import { brief, retryDelay, type ChannelProvider, type SendResult } from "./types";
import type { ClaimedMessage } from "../types";

/**
 * How the connection to your own mail server is secured.
 *   starttls  start plain, then upgrade before anything private is sent (usually port 587). The upgrade is required: if the server does not
 *             offer it, nothing is sent.
 *   tls       encrypted from the first byte (usually port 465).
 *   none      no encryption. Only for a server on the same machine or private network.
 */
export type SmtpSecurity = "starttls" | "tls" | "none";

export type SmtpOptions = {
  host: string;
  port: number;
  security: SmtpSecurity;
  user?: string;
  password?: string;
  /** "United Tribes <hello@your-domain.org>", on a domain your server signs (DKIM) and publishes (SPF). */
  from: string;
  replyTo?: string;
  /** The address bounces are sent back to (the envelope sender). Defaults to the address in `from`. */
  bounceTo?: string;
  /** Names the server to greet with. Defaults to the machine's own name; set it to your site's host name. */
  helloName?: string;
  connectionTimeoutMs?: number;
  socketTimeoutMs?: number;
  /** For tests: builds the transport from the options. */
  createTransport?: (options: SMTPTransport.Options) => Mailer;
};

/** The one thing used from the mail library, so a test can stand in for it. */
export type Mailer = {
  sendMail(mail: ReturnType<SmtpEmailSender["mail"]>): Promise<{ messageId?: string; accepted?: unknown[]; rejected?: unknown[] }>;
};

const addressOf = (from: string) => (/<([^<>]+)>/.exec(from)?.[1] ?? from).trim();
const domainOf = (address: string) => address.split("@")[1]?.toLowerCase() || "localhost";

/** The reply codes a mail server uses for "not now" (4xx) and "never" (5xx). */
type SmtpError = Error & { code?: string; responseCode?: number; response?: string; command?: string };

/**
 * Sends email through your own SMTP server.
 *
 * A message gets one stable Message-ID made from its id and attempt number, so a retry after a timeout can be recognised in your server's
 * log. SMTP has no idempotency key: if the server accepts a message and the connection then drops before it says so, the retry can send a
 * second copy. That is rare, and the alternative (not retrying) loses messages.
 */
export class SmtpEmailSender implements ChannelProvider {
  readonly channel = "email" as const;
  readonly name = "smtp";
  private readonly transport: Mailer;
  private readonly domain: string;

  constructor(private readonly o: SmtpOptions) {
    this.domain = domainOf(addressOf(o.from));
    const options: SMTPTransport.Options = {
      host: o.host,
      port: o.port,
      secure: o.security === "tls",
      ...(o.security === "starttls" ? { requireTLS: true } : {}),
      ...(o.security === "none" ? { ignoreTLS: true } : {}),
      ...(o.user ? { auth: { user: o.user, pass: o.password ?? "" } } : {}),
      ...(o.helloName ? { name: o.helloName } : {}),
      // A serverless function must not wait for minutes on a server that does not answer.
      connectionTimeout: o.connectionTimeoutMs ?? 10_000,
      greetingTimeout: o.connectionTimeoutMs ?? 10_000,
      socketTimeout: o.socketTimeoutMs ?? 30_000,
      // The certificate is always checked; a name that does not match the certificate is a failure, not a warning.
      tls: { rejectUnauthorized: true, minVersion: "TLSv1.2" },
    };
    this.transport = o.createTransport ? o.createTransport(options) : nodemailer.createTransport(options);
  }

  /** What is handed to the mail library. Public so a test can read it. */
  mail(msg: ClaimedMessage, site: string) {
    const email = renderEmail(msg, site);
    const to = (msg.to.email ?? "").trim();
    return {
      from: this.o.from,
      to,
      ...(this.o.replyTo ? { replyTo: this.o.replyTo } : {}),
      subject: email.subject,
      html: email.html,
      text: email.text,
      messageId: `<ut-${msg.id}-${msg.attempts}@${this.domain}>`,
      // The envelope sender is where bounces land. It is the sending address unless a separate bounce mailbox is set.
      envelope: { from: addressOf(this.o.bounceTo || this.o.from), to },
      headers: {
        ...(msg.urgency === "urgent" ? { Importance: "high", "X-Priority": "1" } : {}),
        // Mail that was generated by a program says so, so out-of-office replies do not answer it.
        "Auto-Submitted": "auto-generated",
        ...(email.headers ?? {}),
      },
    };
  }

  async send(msg: ClaimedMessage, site: string): Promise<SendResult> {
    const to = (msg.to.email ?? "").trim();
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(to)) return { ok: false, kind: "rejected", error: "no email address" };

    try {
      const info = await this.transport.sendMail(this.mail(msg, site));
      const refused = Array.isArray(info.rejected) ? info.rejected : [];
      if (refused.length > 0 && (!Array.isArray(info.accepted) || info.accepted.length === 0)) {
        return { ok: false, kind: "rejected", error: "smtp: the server refused this address" };
      }
      return { ok: true, providerId: typeof info.messageId === "string" ? info.messageId : null };
    } catch (caught) {
      return classifySmtpError(caught as SmtpError, msg.attempts);
    }
  }
}

/**
 * Decides whether a failure is worth trying again.
 *   4xx replies (busy, greylisted, mailbox temporarily full, too many connections) and anything that stops the connection: try again later.
 *   Login refused and a refused address or message (5xx): this channel will not work for this person now, so the next channel gets a chance.
 */
export function classifySmtpError(error: SmtpError, attempts: number): SendResult {
  const text = brief(`${error.response ?? error.message ?? ""}`);
  const code = error.code ?? "";
  const reply = typeof error.responseCode === "number" ? error.responseCode : 0;
  const retry = (label: string): SendResult => ({ ok: false, kind: "retry", error: label, retryMinutes: retryDelay(null, attempts) });

  if (reply >= 400 && reply < 500) return retry(`smtp ${reply}: ${text}`);
  if (code === "EAUTH") return { ok: false, kind: "rejected", error: `smtp login refused${reply ? ` (${reply})` : ""}` };
  if (reply >= 500) return { ok: false, kind: "rejected", error: `smtp ${reply}: ${text}` };
  if (code === "EENVELOPE" || code === "EMESSAGE") return { ok: false, kind: "rejected", error: `smtp: ${text || "message refused"}` };
  // No reply at all: the server could not be reached, took too long, hung up, or has no usable certificate. A certificate fault is
  // a set-up problem, but it can be mended while the message waits, so it is tried again rather than lost.
  const label = code === "ETIMEDOUT" || code === "ESOCKET" || code === "ECONNECTION" || code === "ECONNREFUSED" || code === "EDNS" ? "email server unreachable" : `email server: ${text || code || "failed"}`;
  return retry(label);
}
