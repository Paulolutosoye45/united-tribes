select s.id as season_id,
       s.name as season,
       k.taken_on,
       k.week,
       (k.data ->> 'members')::int as members,
       (k.data ->> 'attendance_rate')::numeric as attendance_rate,
       (k.data ->> 'retention_rate')::numeric as retention_rate,
       (k.data ->> 'belong')::numeric as thriving_rate,
       (k.data ->> 'word')::numeric as word_habit_rate,
       (k.data ->> 'goal')::numeric as goal_gain_share,
       (k.data ->> 'care')::numeric as care_resolved_rate,
       (k.data ->> 'multiply')::numeric as assistants_per_circle,
