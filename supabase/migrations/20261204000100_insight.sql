-- ---------------------------------------------------------------------------
-- The nine objectives, worked out from the same rows as the dashboard (internal)
-- ---------------------------------------------------------------------------

create function public.insight_data(p_season uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  s public.seasons%rowtype;
  today date := public.today_lagos();
  tg jsonb := public.kpi_targets();
  cw integer;
  gone integer;
  mincell integer := (tg ->> 'min_cell')::int;
  minans integer := (tg ->> 'min_answers')::int;
  gmin integer := (tg ->> 'gain_min')::int;
  v_measured boolean;
  v_members integer;
  v_thriving integer;
  v_gain_n integer;
  v_gain_ok integer;
  v_hi_n integer; v_hi_ok integer; v_lo_n integer; v_lo_ok integer;
  v_thriving_rate numeric;
  v_gain_share numeric;
  v_gap numeric;
  v_connect_n integer; v_connect_median numeric;
  v_form_n integer; v_form_median numeric;
  v_finished integer; v_started integer; v_completion numeric;
  v_choose_n integer; v_choose_median numeric;
  v_word_n integer; v_word_keep integer; v_word_rate numeric;
  v_care_n integer; v_care_ok integer; v_care_rate numeric; v_urgent_n integer; v_urgent_ok integer;
  v_circles_n integer; v_assist_n integer;
  v_ai jsonb;
  v_ai_low numeric; v_ai_low_field text; v_ai_fields integer;
  v_times_shown integer; v_times_kept integer;
  v_kpis jsonb;
  v_goals jsonb;
begin
  select * into s from public.seasons where id = p_season;
  if not found then
    return jsonb_build_object('state', 'none', 'targets', tg);
  end if;
  cw := public.season_week(s.starts_on, s.weeks, today);
  gone := case when cw = 0 then 0 when cw > s.weeks then s.weeks else cw - 1 end;
  v_measured := gone >= (tg ->> 'min_weeks')::int;

  -- Belong, achieve the goal, match well
  select count(*)::int, count(*) filter (where km_thriving)::int,
         count(km_gain)::int, count(*) filter (where km_gain >= gmin)::int,
         count(*) filter (where km_degree >= 85)::int, count(*) filter (where km_degree >= 85 and km_thriving)::int,
         count(*) filter (where km_degree between 60 and 69)::int, count(*) filter (where km_degree between 60 and 69 and km_thriving)::int
    into v_members, v_thriving, v_gain_n, v_gain_ok, v_hi_n, v_hi_ok, v_lo_n, v_lo_ok
    from public.kpi_members(p_season);
  v_thriving_rate := case when v_measured and v_members > 0 then round(v_thriving::numeric / v_members, 3) end;
  v_gain_share := case when v_gain_n >= minans then round(v_gain_ok::numeric / v_gain_n, 3) end;
  v_gap := case when v_measured and v_hi_n >= mincell and v_lo_n >= mincell
                then round(v_hi_ok::numeric / v_hi_n - v_lo_ok::numeric / v_lo_n, 3) end;

  -- Connect fast: the day the form was submitted to the first held meeting they came to
  with first_meet as (
    select m.person_id, min(public.meeting_date_of(m.circle_id, a.week)) as d
      from public.circle_members m
      join public.circle_attendance a on a.circle_id = m.circle_id and a.person_id = m.person_id and a.status = 'present'
      join public.circle_logs l on l.circle_id = a.circle_id and l.week = a.week and l.held
     where m.season_id = p_season and m.status = 'active'
     group by m.person_id)
  select count(*)::int,
         percentile_cont(0.5) within group (order by greatest(0, f.d - (mp.submitted_at at time zone 'Africa/Lagos')::date))
    into v_connect_n, v_connect_median
    from first_meet f join public.member_profiles mp on mp.person_id = f.person_id;

  -- Match effortlessly: time on the form, started forms finished, and the wait from finishing to choosing
  select count(*)::int, percentile_cont(0.5) within group (order by mp.duration_seconds) / 60.0
    into v_form_n, v_form_median
    from public.member_profiles mp
   where mp.season_id = p_season and mp.duration_seconds is not null and mp.duration_seconds > 0;
  select count(*)::int into v_finished from public.member_profiles where season_id = p_season;
  v_started := v_finished + (select count(*)::int from public.intake_drafts);
  v_completion := case when v_started >= mincell then round(v_finished::numeric / v_started, 3) end;
  select count(*)::int, percentile_cont(0.5) within group (order by extract(epoch from m.joined_at - mp.submitted_at) / 86400.0)
    into v_choose_n, v_choose_median
    from public.circle_members m
    join public.member_profiles mp on mp.person_id = m.person_id and mp.season_id = m.season_id
   where m.season_id = p_season and m.status = 'active' and m.joined_at >= mp.submitted_at;

  -- Grow in faith: members whose last three weekly reports average at least the minimum days in the Word
  with last3 as (
    select w.person_id, w.days, row_number() over (partition by w.person_id order by w.week desc) as rn
      from public.word_habit w join public.circles c on c.id = w.circle_id
     where c.season_id = p_season),
  per as (select person_id, avg(days) as a from last3 where rn <= 3 group by person_id)
  select count(*)::int, count(*) filter (where a >= (tg ->> 'word_days_min')::numeric)::int
    into v_word_n, v_word_keep from per;
  v_word_rate := case when v_word_n >= mincell then round(v_word_keep::numeric / v_word_n, 3) end;

  -- Care well: tasks old enough to judge, resolved within the target days; urgent ones on the same day
  select count(*) filter (where t.status <> 'dismissed' and t.created_at <= now() - make_interval(days => (tg ->> 'care_days')::int))::int,
         count(*) filter (where t.status = 'done' and t.created_at <= now() - make_interval(days => (tg ->> 'care_days')::int)
                            and t.closed_at <= t.created_at + make_interval(days => (tg ->> 'care_days')::int))::int,
         count(*) filter (where t.kind = 'urgent' and t.status <> 'dismissed')::int,
         count(*) filter (where t.kind = 'urgent' and t.status = 'done'
                            and (t.closed_at at time zone 'Africa/Lagos')::date = (t.created_at at time zone 'Africa/Lagos')::date)::int
    into v_care_n, v_care_ok, v_urgent_n, v_urgent_ok
    from public.care_tasks t join public.circles c on c.id = t.circle_id
   where c.season_id = p_season;
  v_care_rate := case when v_care_n >= minans then round(v_care_ok::numeric / v_care_n, 3) end;

  -- Multiply: circles with a certified assistant
  select count(*)::int,
         count(*) filter (where exists (select 1 from public.leader_certifications lc
                                         where lc.person_id = c.assistant_id and lc.as_role = 'assistant_leader'))::int
    into v_circles_n, v_assist_n
    from public.circles c where c.season_id = p_season and c.status = 'approved';

  -- Understand people: for each field the assistant filled, how often the suggestion was kept
  select coalesce(jsonb_agg(jsonb_build_object('field', q.field, 'shown', q.n, 'kept', q.k,
                                               'rate', case when q.n >= minans then round(q.k::numeric / q.n, 3) end) order by q.field), '[]'::jsonb)
    into v_ai
    from (
      select x.field, count(*)::int as n, count(*) filter (where x.kept)::int as k
        from (
          select f.key as field,
                 case
                   when f.key in ('children', 'group_roles')
                     then coalesce(jsonb_array_length(case when jsonb_typeof(f.value -> 'kept') = 'array' then f.value -> 'kept' end), 0) > 0
                   when f.key = 'success_sentence' then (f.value ->> 'chosen') in ('kept', 'edited')
                   else (f.value ->> 'chosen') is not null and (f.value -> 'shown') ? (f.value ->> 'chosen')
                 end as kept
            from public.member_profiles mp
            cross join lateral jsonb_each(case when jsonb_typeof(mp.ai_assist) = 'object' then mp.ai_assist else '{}'::jsonb end) f
           where mp.season_id = p_season and f.key <> 'meeting_times'
             and jsonb_typeof(f.value -> 'shown') = 'array' and jsonb_array_length(f.value -> 'shown') > 0) x
       group by x.field) q;
  select (e ->> 'rate')::numeric, e ->> 'field' into v_ai_low, v_ai_low_field
    from jsonb_array_elements(v_ai) e where e ->> 'rate' is not null
   order by (e ->> 'rate')::numeric, e ->> 'field' limit 1;
  select count(*)::int into v_ai_fields from jsonb_array_elements(v_ai) e where e ->> 'rate' is not null;
  select count(*) filter (where jsonb_typeof(mp.ai_assist -> 'meeting_times' -> 'shown') = 'array'
                            and jsonb_array_length(mp.ai_assist -> 'meeting_times' -> 'shown') > 0)::int,
         count(*) filter (where jsonb_typeof(mp.ai_assist -> 'meeting_times' -> 'kept') = 'array'
                            and jsonb_array_length(mp.ai_assist -> 'meeting_times' -> 'kept') > 0)::int
    into v_times_shown, v_times_kept
    from public.member_profiles mp where mp.season_id = p_season and jsonb_typeof(mp.ai_assist) = 'object';

  v_kpis := jsonb_build_array(
    public.kpi_row('connect', 'Connect fast',
      case when v_connect_n >= minans then round(v_connect_median::numeric, 1) end,
      (tg ->> 'connect_days')::numeric, 'max', v_connect_n, 'days',
      jsonb_build_object('target_alt', (tg ->> 'connect_days_season')::numeric)),
    public.kpi_row('belong', 'Belong', v_thriving_rate, (tg ->> 'thriving_rate')::numeric, 'min', v_members, 'rate',
      jsonb_build_object('measured', v_measured)),
    public.kpi_row('word', 'Grow in faith', v_word_rate, (tg ->> 'word_habit')::numeric, 'min', v_word_n, 'rate',
      jsonb_build_object('coverage', case when v_members > 0 then round(v_word_n::numeric / v_members, 3) end,
                         'days_min', (tg ->> 'word_days_min')::int)),
    public.kpi_row('goal', 'Achieve the goal', v_gain_share, (tg ->> 'effective_gain')::numeric, 'min', v_gain_n, 'rate',
      jsonb_build_object('gain_min', gmin)),
    public.kpi_row('care', 'Care well', v_care_rate, (tg ->> 'care_resolved')::numeric, 'min', v_care_n, 'rate',
      jsonb_build_object('days', (tg ->> 'care_days')::int, 'urgent', v_urgent_n, 'urgent_same_day', v_urgent_ok)),
    public.kpi_row('multiply', 'Multiply',
      case when v_circles_n > 0 then round(v_assist_n::numeric / v_circles_n, 3) end,
      (tg ->> 'assistants')::numeric, 'min', v_circles_n, 'ratio',
      jsonb_build_object('certified', v_assist_n)),
    public.kpi_row('match', 'Match well', v_gap, (tg ->> 'match_gap')::numeric, 'min', v_hi_n + v_lo_n, 'gap',
      jsonb_build_object('high_n', v_hi_n, 'low_n', v_lo_n,
                         'high_rate', case when v_measured and v_hi_n >= mincell then round(v_hi_ok::numeric / v_hi_n, 3) end,
                         'low_rate', case when v_measured and v_lo_n >= mincell then round(v_lo_ok::numeric / v_lo_n, 3) end)),
    public.kpi_row('form_time', 'Match effortlessly',
      case when v_form_n >= minans then round(v_form_median::numeric, 1) end,
      (tg ->> 'form_minutes')::numeric, 'max', v_form_n, 'minutes',
      jsonb_build_object('wait_days', case when v_choose_n >= minans then round(v_choose_median::numeric, 1) end, 'wait_n', v_choose_n)),
    public.kpi_row('form_completion', 'Match effortlessly', v_completion, (tg ->> 'form_completion')::numeric, 'min', v_started, 'rate',
      jsonb_build_object('finished', v_finished, 'started', v_started)),
    public.kpi_row('ai_keep', 'Understand people', v_ai_low, (tg ->> 'ai_keep')::numeric, 'min', v_ai_fields, 'rate',
      jsonb_build_object('lowest_field', v_ai_low_field)));

  -- Success Picture progress by goal
  select coalesce(jsonb_agg(g order by g ->> 'goal', g ->> 'tribe'), '[]'::jsonb) into v_goals
    from (
      select jsonb_build_object(
               'goal', sg.title, 'tribe', t.name, 'members', count(*)::int, 'gain_n', count(k.km_gain)::int,
               'gain_avg', case when count(k.km_gain) >= minans then round(avg(k.km_gain), 1) end,
               'gain_share', case when count(k.km_gain) >= minans
                                  then round(count(*) filter (where k.km_gain >= gmin)::numeric / count(k.km_gain), 3) end) as g
        from public.kpi_members(p_season) k
        join public.circles c on c.id = k.km_circle
        join public.season_goals sg on sg.id = c.season_goal_id
        left join public.tribes t on t.id = c.tribe_id
       group by sg.id, sg.title, t.name) q;

  return jsonb_build_object(
    'state', case when cw = 0 then 'before' when cw > s.weeks then 'complete' else 'running' end,
    'season', jsonb_build_object('id', s.id, 'name', s.name, 'starts_on', s.starts_on, 'ends_on', s.ends_on, 'weeks', s.weeks,
                                 'current_week', case when cw between 1 and s.weeks then cw end, 'weeks_over', gone),
    'measured', v_measured,
    'members', v_members,
    'retention', public.retention_curve(p_season),
    'earlier', coalesce((
      select jsonb_agg(e order by e ->> 'starts_on' desc)
        from (select jsonb_build_object('season_id', x.id, 'name', x.name, 'starts_on', x.starts_on) || public.retention_curve(x.id) as e
                from public.seasons x
               where x.id <> p_season and x.starts_on < s.starts_on and x.centre_id = s.centre_id
               order by x.starts_on desc limit 3) q
       where (e ->> 'cohort')::int > 0), '[]'::jsonb),
    'kpis', v_kpis,
    'ai', jsonb_build_object('fields', v_ai, 'times_shown', v_times_shown, 'times_kept', v_times_kept),
    'goals', v_goals,
    'trend', coalesce((
      select jsonb_agg(jsonb_build_object('taken_on', t.taken_on, 'week', t.week) || t.data order by t.taken_on)
        from (select * from public.kpi_snapshots k where k.season_id = p_season order by k.taken_on desc limit 16) t), '[]'::jsonb),
    'targets', tg);
end;
$$;

-- The same, for people who may read it.
create function public.insight(p_season uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Sign in first' using errcode = '42501';
  end if;
  if not public.has_any_role(array['admin', 'director', 'pastor', 'data_lead']::public.app_role[]) then
    raise exception 'Only the pastorate, directors and the data lead can see the programme figures' using errcode = '42501';
  end if;
  return public.insight_data(public.dashboard_season(p_season));
end;
$$;

-- Writes today's snapshot for a season: the handful of numbers worth drawing as a trend. (internal)
create function public.take_snapshot(p_season uuid, p_now timestamptz default now())
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  s public.seasons%rowtype;
  d jsonb;
  v_today date := (p_now at time zone 'Africa/Lagos')::date;
  v_att numeric;
  v_last jsonb;
  k jsonb;
begin
  select * into s from public.seasons where id = p_season;
  if not found then
    return;
  end if;
  d := public.insight_data(p_season);
  select case when sum(kc_possible) > 0 then round(sum(kc_present)::numeric / sum(kc_possible), 3) end
    into v_att from public.kpi_circles(p_season);
  v_last := (d -> 'retention' -> 'points') -> (jsonb_array_length(d -> 'retention' -> 'points') - 1);
  k := jsonb_build_object(
    'members', d -> 'members',
    'attendance_rate', v_att,
    'retention_rate', v_last -> 'rate',
    'retention_week', v_last -> 'week');
  select k || coalesce(jsonb_object_agg(e ->> 'key', e -> 'value'), '{}'::jsonb) into k
    from jsonb_array_elements(d -> 'kpis') e;
  k := k || jsonb_build_object('open_care', (select count(*) from public.care_tasks t join public.circles c on c.id = t.circle_id
                                               where c.season_id = p_season and t.status = 'open'));
  insert into public.kpi_snapshots (season_id, taken_on, week, data, taken_at)
  values (p_season, v_today, coalesce((d -> 'season' ->> 'weeks_over')::int, 0), k, p_now)
  on conflict (season_id, taken_on) do update set week = excluded.week, data = excluded.data, taken_at = excluded.taken_at;
end;
$$;

-- ---------------------------------------------------------------------------
-- The dashboard, split in two so a tribe champion's page does the same arithmetic as the church dashboard
--
--   dashboard_core(season, circles)   the circles with their verdicts, the headline numbers, week by week
--   church_views(season)              the church-wide views: journey, supply and demand, tribes, matching, care
--   dashboard(season)                 who may see what, then the two above (unchanged for the people who call it)
-- ---------------------------------------------------------------------------

create function public.dashboard_core(p_season uuid, p_scope uuid[])
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  sid uuid := p_season;
  scope uuid[] := coalesce(p_scope, '{}');
  s public.seasons%rowtype;
  today date := public.today_lagos();
  tg jsonb := public.kpi_targets();
  cw integer;
  gone integer;
  mincell integer := (public.kpi_targets() ->> 'min_cell')::int;
  minans integer := (public.kpi_targets() ->> 'min_answers')::int;
  h jsonb;
  circles_json jsonb;
  weeks_json jsonb;
begin
  select * into s from public.seasons where id = sid;
  if not found then
    return jsonb_build_object('circles', '[]'::jsonb, 'headline', '{}'::jsonb, 'weeks', '[]'::jsonb);
  end if;
  cw := public.season_week(s.starts_on, s.weeks, today);
  gone := case when cw = 0 then 0 when cw > s.weeks then s.weeks else cw - 1 end;

  -- The circles, with their numbers and verdict
  select coalesce(jsonb_agg(r order by
           case r ->> 'verdict' when 'at_risk' then 0 when 'not_yet' then 1 when 'close' then 2 when 'too_early' then 3 when 'before' then 4 else 5 end,
           r ->> 'name'), '[]'::jsonb)
    into circles_json
    from (
      select jsonb_build_object(
               'circle_id', c.id, 'name', c.name,
               'leader', public.person_display_name(c.leader_id),
               'coach', case when c.coach_id is null then null else public.person_display_name(c.coach_id) end,
               'tribe', t.name, 'track', tr.name,
               'members', k.kc_members, 'capacity', c.capacity,
               'held', k.kc_held,
               'attendance_rate', case when k.kc_possible > 0 then round(k.kc_present::numeric / k.kc_possible, 3) end,
               'thriving', case when k.kc_measured then k.kc_thriving end,
               'thriving_rate', case when k.kc_measured then round(k.kc_thriving::numeric / k.kc_members, 3) end,
               'gain_n', k.kc_gain_n,
               'gain_avg', case when k.kc_gain_n >= minans then round(k.kc_gain_avg, 1) end,
               'gain_share', case when k.kc_gain_n >= minans then round(k.kc_gain_ok::numeric / k.kc_gain_n, 3) end,
               'steps_done_rate', case when k.kc_checked > 0 then round(k.kc_done::numeric / k.kc_checked, 3) end,
               'verdict', k.kc_verdict) as r
        from public.kpi_circles(sid) k
        join public.circles c on c.id = k.kc_circle
        left join public.tribes t on t.id = c.tribe_id
        left join public.tracks tr on tr.id = c.track_id
       where c.id = any(scope)) q;

  -- The headline numbers, for the circles in scope
  with km as (select * from public.kpi_members(sid) where km_circle = any(scope)),
       kc as (select * from public.kpi_circles(sid) where kc_circle = any(scope))
  select jsonb_build_object(
           'members', (select count(*) from km),
           'circles', (select count(*) from kc),
           'measured', gone >= (tg ->> 'min_weeks')::int,
           'thriving', (select count(*) from km where km_thriving),
           'thriving_rate', case when gone >= (tg ->> 'min_weeks')::int and (select count(*) from km) > 0
                                 then round((select count(*) from km where km_thriving)::numeric / (select count(*) from km), 3) end,
           'attendance_rate', case when (select coalesce(sum(kc_possible), 0) from kc) > 0
                                   then round((select sum(kc_present) from kc)::numeric / (select sum(kc_possible) from kc), 3) end,
           'base_n', (select count(km_base) from km),
           'base_avg', case when (select count(km_base) from km) >= minans then round((select avg(km_base) from km), 1) end,
           'latest_avg', case when (select count(km_latest) from km) >= minans then round((select avg(km_latest) from km), 1) end,
           'gain_n', (select count(km_gain) from km),
           'gain_avg', case when (select count(km_gain) from km) >= minans then round((select avg(km_gain) from km), 1) end,
           'gain_share', case when (select count(km_gain) from km) >= minans
                              then round((select count(*) filter (where km_gain >= (tg ->> 'gain_min')::int) from km)::numeric / (select count(km_gain) from km), 3) end,
           'steps_done_rate', case when (select coalesce(sum(km_checked), 0) from km) > 0
                                   then round((select sum(km_done) from km)::numeric / (select sum(km_checked) from km), 3) end,
           'checkin_rate', case when (select coalesce(sum(km_set), 0) from km) > 0
                                then round((select sum(km_checked) from km)::numeric / (select sum(km_set) from km), 3) end,
           'ever_came', (select count(*) from km where km_attended > 0),
           'still_coming', (select count(*) from km where km_attended > 0 and km_recent > 0),
           'verdicts', jsonb_build_object(
             'effective', (select count(*) from kc where kc_verdict = 'effective'),
             'not_yet', (select count(*) from kc where kc_verdict = 'not_yet'),
             'on_course', (select count(*) from kc where kc_verdict = 'on_course'),
             'close', (select count(*) from kc where kc_verdict = 'close'),
             'at_risk', (select count(*) from kc where kc_verdict = 'at_risk')))
    into h;

  -- Week by week, for the circles in scope
  select coalesce(jsonb_agg(w order by (w ->> 'week')::int), '[]'::jsonb) into weeks_json
    from (
      select jsonb_build_object(
               'week', g.w,
               'current', cw = g.w,
               'logged', (select count(*) from public.circle_logs l where l.week = g.w and l.circle_id = any(scope)),
               'met', (select count(*) from public.circle_logs l where l.week = g.w and l.held and l.circle_id = any(scope)),
               'present', (select count(*) from public.circle_attendance a
                            join public.circle_logs l on l.circle_id = a.circle_id and l.week = a.week and l.held
                           where a.week = g.w and a.status = 'present' and a.circle_id = any(scope)),
               'possible', (select count(*) from public.circle_attendance a
                             join public.circle_logs l on l.circle_id = a.circle_id and l.week = a.week and l.held
                            where a.week = g.w and a.circle_id = any(scope)),
               'steps_set', (select count(*) from public.week_steps ws where ws.week = g.w and ws.circle_id = any(scope)),
               'steps_done', (select count(*) from public.week_steps ws where ws.week = g.w and ws.outcome = 'done' and ws.circle_id = any(scope)),
               'steps_checked', (select count(*) from public.week_steps ws where ws.week = g.w and ws.outcome is not null and ws.circle_id = any(scope))) as w
        from generate_series(1, case when cw = 0 then 0 else least(cw, s.weeks) end) as g(w)) q;


  return jsonb_build_object('circles', circles_json, 'headline', h, 'weeks', weeks_json);
end;
$$;

create function public.church_views(p_season uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  sid uuid := p_season;
  s public.seasons%rowtype;
  today date := public.today_lagos();
  tg jsonb := public.kpi_targets();
  cw integer;
  gone integer;
  mincell integer := (public.kpi_targets() ->> 'min_cell')::int;
  minans integer := (public.kpi_targets() ->> 'min_answers')::int;
begin
  select * into s from public.seasons where id = sid;
  if not found then
    return '{}'::jsonb;
  end if;
  cw := public.season_week(s.starts_on, s.weeks, today);
  gone := case when cw = 0 then 0 when cw > s.weeks then s.weeks else cw - 1 end;

  return jsonb_build_object(
    'funnel', jsonb_build_array(
      jsonb_build_object('key', 'started', 'label', 'Started the form',
        'count', (select count(*) from public.intake_drafts) + (select count(*) from public.member_profiles where season_id = sid)),
      jsonb_build_object('key', 'finished', 'label', 'Finished the form',
        'count', (select count(*) from public.member_profiles where season_id = sid)),
      jsonb_build_object('key', 'shown', 'label', 'Were shown circles',
        'count', (select count(distinct r.person_id) from public.match_runs r where r.season_id = sid and r.shown > 0)),
      jsonb_build_object('key', 'chose', 'label', 'Chose a circle',
        'count', (select count(distinct m.person_id) from public.circle_members m where m.season_id = sid and m.status = 'active')),
      jsonb_build_object('key', 'came', 'label', 'Came to a meeting',
        'count', (select count(*) from public.kpi_members(sid) where km_attended > 0)),
      jsonb_build_object('key', 'thriving', 'label', 'Thriving',
        'count', (select count(*) from public.kpi_members(sid) where km_thriving))),

    'supply', (
      with w as (
        select mp.tribe_id, ar.track_id, count(*)::int as n
          from public.member_profiles mp
          join public.age_ranges ar on ar.id = mp.age_range_id
         where mp.season_id = sid and mp.tribe_id is not null
         group by mp.tribe_id, ar.track_id),
      seats as (
        select c.tribe_id, c.track_id, sum(c.capacity)::int as seats
          from public.circles c
         where c.season_id = sid and c.status = 'approved'
           and exists (select 1 from public.leader_certifications lc where lc.person_id = c.leader_id)
         group by c.tribe_id, c.track_id),
      placed as (
        select c.tribe_id, c.track_id, count(*)::int as placed
          from public.circle_members m
          join public.circles c on c.id = m.circle_id
         where m.status = 'active' and c.season_id = sid
         group by c.tribe_id, c.track_id),
      cells as (
        select coalesce(w.tribe_id, seats.tribe_id, placed.tribe_id) as tribe_id,
               coalesce(w.track_id, seats.track_id, placed.track_id) as track_id,
               coalesce(w.n, 0) as wants, coalesce(seats.seats, 0) as seats, coalesce(placed.placed, 0) as placed
          from w
          full join seats on seats.tribe_id = w.tribe_id and seats.track_id = w.track_id
          full join placed on placed.tribe_id = coalesce(w.tribe_id, seats.tribe_id)
                          and placed.track_id = coalesce(w.track_id, seats.track_id))
      select jsonb_build_object(
        'tribes', (select coalesce(jsonb_agg(t.name order by t.sort), '[]'::jsonb) from public.tribes t where t.active),
        'tracks', (select coalesce(jsonb_agg(tr.name order by tr.sort), '[]'::jsonb) from public.tracks tr where tr.active),
        'cells', (select coalesce(jsonb_agg(jsonb_build_object('tribe', t.name, 'track', tr.name, 'wants', c.wants, 'seats', c.seats, 'placed', c.placed)), '[]'::jsonb)
                    from cells c join public.tribes t on t.id = c.tribe_id join public.tracks tr on tr.id = c.track_id),
        'wants', (select coalesce(sum(wants), 0) from cells),
        'seats', (select coalesce(sum(seats), 0) from cells),
        'placed', (select coalesce(sum(placed), 0) from cells),
        'unmet', (select count(*) from public.match_demand d where d.season_id = sid))),

    'tribes', (
      select coalesce(jsonb_agg(x order by (x ->> 'members')::int desc, x ->> 'tribe'), '[]'::jsonb)
        from (
          select jsonb_build_object(
                   'tribe', t.name,
                   'members', count(*),
                   'thriving_rate', case when count(*) >= mincell and gone >= (tg ->> 'min_weeks')::int
                                         then round(count(*) filter (where k.km_thriving)::numeric / count(*), 3) end,
                   'gain_avg', case when count(k.km_gain) >= minans then round(avg(k.km_gain), 1) end) as x
            from public.kpi_members(sid) k
            join public.circles c on c.id = k.km_circle
            join public.tribes t on t.id = c.tribe_id
           group by t.name) q),

    'accuracy', (
      with km as (select * from public.kpi_members(sid))
      select jsonb_build_object(
        'bands', (select jsonb_agg(b order by (b ->> 'sort')::int)
                    from (
                      select jsonb_build_object(
                               'key', v.key, 'label', v.label, 'sort', v.sort,
                               'n', count(km.km_person),
                               'thriving_rate', case when count(km.km_person) >= mincell and gone >= (tg ->> 'min_weeks')::int
                                                     then round(count(*) filter (where km.km_thriving)::numeric / count(km.km_person), 3) end,
                               'attendance_rate', case when count(km.km_person) >= mincell and gone > 0
                                                       then round(avg(km.km_attended::numeric / nullif(gone, 0)), 3) end) as b
                        from (values ('excellent', 'Excellent (85–100)', 1, 85, 100),
                                     ('strong', 'Strong (70–84)', 2, 70, 84),
                                     ('good', 'Good (60–69)', 3, 60, 69)) as v(key, label, sort, lo, hi)
                        left join km on km.km_degree between v.lo and v.hi
                       group by v.key, v.label, v.sort) q),
        'ranks', (select jsonb_agg(b order by (b ->> 'rank')::int)
                    from (
                      select jsonb_build_object(
                               'rank', v.rank, 'label', v.label,
                               'n', count(km.km_person),
                               'thriving_rate', case when count(km.km_person) >= mincell and gone >= (tg ->> 'min_weeks')::int
                                                     then round(count(*) filter (where km.km_thriving)::numeric / count(km.km_person), 3) end,
                               'attendance_rate', case when count(km.km_person) >= mincell and gone > 0
                                                       then round(avg(km.km_attended::numeric / nullif(gone, 0)), 3) end) as b
                        from (values (1, 'Their first card'), (2, 'Their second card'), (3, 'Their third card')) as v(rank, label)
                        left join km on km.km_rank = v.rank
                       group by v.rank, v.label) q),
        'average_degree', (select round(avg(km_degree)) from km),
        'completed', (select count(*) from public.circle_members m
                       join public.circles c on c.id = m.circle_id
                       join public.seasons x on x.id = c.season_id
                      where m.status = 'active' and public.season_week(x.starts_on, x.weeks, today) > x.weeks),
        'retrain_after', (tg ->> 'retrain_after')::int)),

    'care', (
      select jsonb_build_object(
        'open', count(*) filter (where f.status = 'open'),
        'escalated', count(*) filter (where f.status = 'escalated'),
        'oldest_open_days', (select max(today - (g.opened_at at time zone 'Africa/Lagos')::date)
                               from public.care_flags g join public.circles gc on gc.id = g.circle_id
                              where g.status <> 'closed' and gc.season_id = sid),
        'closed_7d', count(*) filter (where f.status = 'closed' and f.closed_at >= now() - interval '7 days'),
        'median_days_to_close', (select round(percentile_cont(0.5) within group (order by extract(epoch from (g.closed_at - g.opened_at)) / 86400)::numeric, 1)
                                   from public.care_flags g join public.circles gc on gc.id = g.circle_id
                                  where g.status = 'closed' and g.closed_at is not null and gc.season_id = sid))
        from public.care_flags f join public.circles fc on fc.id = f.circle_id
       where fc.season_id = sid),

    'testimonies', (
      select jsonb_build_object(
        'waiting', count(*) filter (where t.status = 'submitted'),
        'circle', count(*) filter (where t.status = 'circle_approved'),
        'church', count(*) filter (where t.status = 'church_approved'),
        'declined', count(*) filter (where t.status = 'declined'))
        from public.testimonies t join public.circles tc on tc.id = t.circle_id
       where tc.season_id = sid));
end;
$$;

create or replace function public.dashboard(p_season uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  church boolean := public.has_any_role(array['admin', 'director', 'pastor', 'data_lead']::public.app_role[]);
  is_coach boolean := public.has_any_role(array['coach']::public.app_role[]);
  sid uuid;
  s public.seasons%rowtype;
  today date := public.today_lagos();
  tg jsonb := public.kpi_targets();
  cw integer;
  gone integer;
  need integer;
  state text;
  scope uuid[];
  core jsonb;
  seasons_json jsonb;
  result jsonb;
begin
  if uid is null then
    raise exception 'Sign in first' using errcode = '42501';
  end if;
  if not (church or is_coach) then
    raise exception 'Only the pastorate, directors, the data lead and coaches can see the dashboard' using errcode = '42501';
  end if;

  sid := public.dashboard_season(p_season);
  select * into s from public.seasons where id = sid;
  if not found then
    return jsonb_build_object('state', 'none', 'targets', tg);
  end if;
  cw := public.season_week(s.starts_on, s.weeks, today);
  gone := case when cw = 0 then 0 when cw > s.weeks then s.weeks else cw - 1 end;
  need := ceil(round(s.weeks * (tg ->> 'attend_share')::numeric, 4))::int;
  state := case when cw = 0 then 'before' when cw > s.weeks then 'complete' else 'running' end;

  -- A coach sees only their own circles
  select coalesce(array_agg(c.id), '{}') into scope
    from public.circles c
   where c.season_id = sid and c.status = 'approved'
     and (church or c.coach_id = uid);

  select coalesce(jsonb_agg(jsonb_build_object('id', x.id, 'name', x.name, 'starts_on', x.starts_on, 'weeks', x.weeks) order by x.starts_on desc), '[]'::jsonb)
    into seasons_json from public.seasons x where x.centre_id = s.centre_id;

  core := public.dashboard_core(sid, scope);

  result := jsonb_build_object(
    'state', state,
    'scope', case when church then 'church' else 'coach' end,
    'targets', tg,
    'season', jsonb_build_object('id', s.id, 'name', s.name, 'starts_on', s.starts_on, 'weeks', s.weeks,
                                 'current_week', case when cw between 1 and s.weeks then cw end,
                                 'weeks_over', gone, 'meetings_needed', need),
    'seasons', seasons_json,
    'headline', core -> 'headline',
    'weeks', core -> 'weeks',
    'circles', core -> 'circles');

  if not church then
    return result;
  end if;
  return result || public.church_views(sid);
end;
$$;

-- A rate hidden when too few people stand behind it, so nobody's belonging answer can be guessed from it.
-- Used for the tribe champion's page and the tribe reports.
create function public.hide_small_cells(p_circles jsonb, p_min integer)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select coalesce(jsonb_agg(
           case when coalesce((c ->> 'members')::int, 0) >= p_min then c
                else (c - 'thriving' - 'thriving_rate' - 'gain_avg' - 'gain_share' - 'verdict') || jsonb_build_object('verdict', 'small')
           end order by ord), '[]'::jsonb)
    from jsonb_array_elements(coalesce(p_circles, '[]'::jsonb)) with ordinality as t(c, ord);
$$;

create function public.hide_small_headline(p_headline jsonb, p_min integer)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select case when coalesce((p_headline ->> 'members')::int, 0) >= p_min then p_headline
              else p_headline - 'thriving' - 'thriving_rate' - 'base_avg' - 'latest_avg' - 'gain_avg' - 'gain_share' - 'verdicts' end;
$$;

-- ---------------------------------------------------------------------------
-- The reports
--
--   programme   the monthly report for the directors and the pastorate: everything, with the trend
--   pastorate   the one-page monthly summary for the senior pastor
--   tribe       one tribe's month, for its champions
--   season      the end-of-season report
--
-- A report stores the figures it was made from, so it reads the same next year.
-- ---------------------------------------------------------------------------

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  centre_id uuid not null references public.centres (id),
  kind text not null check (kind in ('programme', 'pastorate', 'tribe', 'season')),
  period_start date not null,
  period_end date not null,
  season_id uuid not null references public.seasons (id) on delete cascade,
  tribe_id uuid references public.tribes (id) on delete cascade,
  data jsonb not null,
  summary text check (char_length(summary) <= 2400),
  summary_by text check (summary_by in ('assistant', 'plain', 'edited')),
  generated_at timestamptz not null default now(),
  generated_by uuid references public.people (id) on delete set null,
  check (period_end >= period_start),
  check ((kind = 'tribe') = (tribe_id is not null)),
  check ((summary is null) = (summary_by is null)),
  constraint reports_one unique nulls not distinct (kind, period_start, season_id, tribe_id)
);
create index reports_season_idx on public.reports (season_id, kind, period_start desc);
create index reports_pending_idx on public.reports (generated_at) where summary is null;
alter table public.reports enable row level security;
-- No grants: only the functions touch this table.

-- What happened inside a window of dates, for the circles given. (internal)
create function public.report_window_facts(p_season uuid, p_scope uuid[], p_start date, p_end date, p_tribe uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_held integer;
  v_present integer;
  v_possible integer;
  v_joined integer;
  v_left integer;
  v_forms integer;
  v_care_opened integer;
  v_care_closed integer;
  v_care_open integer;
  v_urgent integer;
  v_t_new integer;
  v_t_church integer;
begin
  select count(*)::int into v_held
    from public.circle_logs l
   where l.held and l.circle_id = any (p_scope)
     and public.meeting_date_of(l.circle_id, l.week) between p_start and p_end;
  select count(a.person_id) filter (where a.status = 'present')::int, count(a.person_id)::int
    into v_present, v_possible
    from public.circle_logs l
    join public.circle_attendance a on a.circle_id = l.circle_id and a.week = l.week
   where l.held and l.circle_id = any (p_scope)
     and public.meeting_date_of(l.circle_id, l.week) between p_start and p_end;
  select count(*) filter (where (m.joined_at at time zone 'Africa/Lagos')::date between p_start and p_end)::int,
         count(*) filter (where (m.released_at at time zone 'Africa/Lagos')::date between p_start and p_end)::int
    into v_joined, v_left
    from public.circle_members m where m.circle_id = any (p_scope);
  select count(*)::int into v_forms
    from public.member_profiles mp
   where mp.season_id = p_season and (p_tribe is null or mp.tribe_id = p_tribe)
     and (mp.submitted_at at time zone 'Africa/Lagos')::date between p_start and p_end;
  select count(*) filter (where (t.created_at at time zone 'Africa/Lagos')::date between p_start and p_end and t.status <> 'dismissed')::int,
         count(*) filter (where t.status = 'done' and (t.closed_at at time zone 'Africa/Lagos')::date between p_start and p_end)::int,
         count(*) filter (where t.status = 'open')::int,
         count(*) filter (where t.kind = 'urgent' and (t.created_at at time zone 'Africa/Lagos')::date between p_start and p_end)::int
    into v_care_opened, v_care_closed, v_care_open, v_urgent
    from public.care_tasks t where t.circle_id = any (p_scope);
  select count(*) filter (where (t.created_at at time zone 'Africa/Lagos')::date between p_start and p_end)::int,
         count(*) filter (where t.status = 'church_approved' and (t.decided_at at time zone 'Africa/Lagos')::date between p_start and p_end)::int
    into v_t_new, v_t_church
    from public.testimonies t where t.circle_id = any (p_scope);
  return jsonb_build_object(
    'meetings_held', v_held,
    'present', v_present, 'possible', v_possible,
    'attendance_rate', case when v_possible > 0 then round(v_present::numeric / v_possible, 3) end,
    'joined', v_joined, 'left', v_left,
    'forms_finished', v_forms,
    'care_opened', v_care_opened, 'care_closed', v_care_closed, 'care_open_now', v_care_open, 'urgent_opened', v_urgent,
    'testimonies_new', v_t_new, 'testimonies_to_church', v_t_church);
end;
$$;

-- Testimonies the church has approved inside the window, worded as their authors allowed. (internal)
create function public.report_testimonies(p_season uuid, p_start date, p_end date, p_tribe uuid, p_limit integer)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(x.j order by x.decided desc), '[]'::jsonb)
    from (
      select t.decided_at as decided,
             jsonb_build_object(
               'who', case t.credit when 'full_name' then public.person_display_name(t.person_id)
                                    when 'first_name' then public.first_name_of(t.person_id)
                                    else 'A member' end,
               'body', t.body,
               'tribe', tr.name,
               'goal', sg.title,
               'themes', to_jsonb(t.themes)) as j
        from public.testimonies t
        join public.circles c on c.id = t.circle_id
        left join public.tribes tr on tr.id = coalesce(t.tribe_id, c.tribe_id)
        left join public.season_goals sg on sg.id = coalesce(t.season_goal_id, c.season_goal_id)
       where c.season_id = p_season and t.status = 'church_approved'
         and (t.decided_at at time zone 'Africa/Lagos')::date between p_start and p_end
         and (p_tribe is null or coalesce(t.tribe_id, c.tribe_id) = p_tribe)
       order by t.decided_at desc
       limit greatest(p_limit, 0)) x;
$$;

-- How the main numbers moved across the window, from the daily snapshots. Null when there is only one point.
create function public.report_movement(p_season uuid, p_start date, p_end date)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  a public.kpi_snapshots%rowtype;
  b public.kpi_snapshots%rowtype;
begin
  select * into b from public.kpi_snapshots k where k.season_id = p_season and k.taken_on <= p_end order by k.taken_on desc limit 1;
  if not found or b.taken_on < p_start then
    return null;
  end if;
  select * into a from public.kpi_snapshots k where k.season_id = p_season and k.taken_on < p_start order by k.taken_on desc limit 1;
  if not found then
    select * into a from public.kpi_snapshots k where k.season_id = p_season and k.taken_on between p_start and p_end order by k.taken_on asc limit 1;
  end if;
  if a.id = b.id then
    return null;
  end if;
  return jsonb_build_object(
    'from', jsonb_build_object('taken_on', a.taken_on, 'week', a.week) || a.data,
    'to', jsonb_build_object('taken_on', b.taken_on, 'week', b.week) || b.data);
end;
$$;

-- The figures for one report. Figures that are "so far" are as at today; the window facts are for the window. (internal)
create function public.build_report(p_kind text, p_start date, p_end date, p_season uuid, p_tribe uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  s public.seasons%rowtype;
  tg jsonb := public.kpi_targets();
  mincell integer := (public.kpi_targets() ->> 'min_cell')::int;
  today date := public.today_lagos();
  v_scope uuid[];
  v_core jsonb;
  v_ins jsonb;
  v_church jsonb;
  v_tribe public.tribes%rowtype;
  v_out jsonb;
  v_watch jsonb;
  cw integer;
begin
  if p_kind not in ('programme', 'pastorate', 'tribe', 'season') then
    raise exception 'That is not a kind of report' using errcode = '22023';
  end if;
  select * into s from public.seasons where id = p_season;
  if not found then
    raise exception 'We could not find that season' using errcode = 'P0002';
  end if;
  if p_kind = 'tribe' then
    select * into v_tribe from public.tribes where id = p_tribe;
    if not found then
      raise exception 'We could not find that tribe' using errcode = 'P0002';
    end if;
  end if;
  cw := public.season_week(s.starts_on, s.weeks, today);
  select coalesce(array_agg(c.id), '{}') into v_scope
    from public.circles c
   where c.season_id = p_season and c.status = 'approved' and (p_kind <> 'tribe' or c.tribe_id = p_tribe);
  v_core := public.dashboard_core(p_season, v_scope);

  -- Circles that need a look, hardest first (a tribe report hides circles too small to show)
  select coalesce(jsonb_agg(w.c order by w.ord), '[]'::jsonb) into v_watch
    from (
      select e.c, e.ord
        from jsonb_array_elements(case when p_kind = 'tribe' then public.hide_small_cells(v_core -> 'circles', mincell)
                                       else v_core -> 'circles' end) with ordinality as e(c, ord)
       where e.c ->> 'verdict' in ('at_risk', 'not_yet', 'close')
       order by e.ord
       limit 8) w;

  v_out := jsonb_build_object(
    'kind', p_kind,
    'as_of', today,
    'period', jsonb_build_object('start', p_start, 'end', p_end),
    'season', jsonb_build_object('id', s.id, 'name', s.name, 'starts_on', s.starts_on, 'ends_on', s.ends_on, 'weeks', s.weeks,
                                 'current_week', case when cw between 1 and s.weeks then cw end,
                                 'over', cw > s.weeks, 'before', cw = 0),
    'targets', tg,
    'headline', case when p_kind = 'tribe' then public.hide_small_headline(v_core -> 'headline', mincell) else v_core -> 'headline' end,
    'window', public.report_window_facts(p_season, v_scope, p_start, p_end, case when p_kind = 'tribe' then p_tribe end),
    'testimonies', public.report_testimonies(p_season, p_start, p_end, case when p_kind = 'tribe' then p_tribe end,
                                             case p_kind when 'pastorate' then 3 when 'season' then 12 else 8 end),
    'watch', v_watch);

  if p_kind = 'tribe' then
    v_church := public.church_views(p_season);
    v_out := v_out || jsonb_build_object(
      'tribe', jsonb_build_object('id', v_tribe.id, 'name', v_tribe.name),
      'circles', public.hide_small_cells(v_core -> 'circles', mincell),
      'weeks', v_core -> 'weeks',
      'supply', coalesce((select jsonb_agg(e) from jsonb_array_elements(v_church -> 'supply' -> 'cells') e
                           where e ->> 'tribe' = v_tribe.name), '[]'::jsonb));
    return v_out;
  end if;

  v_ins := public.insight_data(p_season);
  v_out := v_out || jsonb_build_object(
    'kpis', v_ins -> 'kpis',
    'movement', public.report_movement(p_season, p_start, p_end));

  if p_kind = 'pastorate' then
    v_church := public.church_views(p_season);
    v_out := v_out || jsonb_build_object('care', v_church -> 'care');
    return v_out;
  end if;

  -- programme and season: the whole picture
  v_church := public.church_views(p_season);
  v_out := v_out || jsonb_build_object(
    'retention', v_ins -> 'retention',
    'ai', v_ins -> 'ai',
    'goals', v_ins -> 'goals',
    'funnel', v_church -> 'funnel',
    'tribes', v_church -> 'tribes',
    'supply', jsonb_build_object('wants', v_church -> 'supply' -> 'wants', 'seats', v_church -> 'supply' -> 'seats',
                                 'placed', v_church -> 'supply' -> 'placed', 'unmet', v_church -> 'supply' -> 'unmet'),
    'accuracy', v_church -> 'accuracy',
    'care', v_church -> 'care');
  if p_kind = 'season' then
    v_out := v_out || jsonb_build_object('earlier', v_ins -> 'earlier', 'circles', v_core -> 'circles', 'weeks', v_core -> 'weeks');
  end if;
  return v_out;
end;
$$;

-- Makes (or remakes) one report. A summary someone has edited by hand is kept. (internal)
create function public.make_report(p_kind text, p_start date, p_end date, p_season uuid, p_tribe uuid, p_by uuid default null)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id uuid;
  v_centre uuid;
begin
  select s.centre_id into v_centre from public.seasons s where s.id = p_season;
  if v_centre is null then
    raise exception 'We could not find that season' using errcode = 'P0002';
  end if;
  insert into public.reports (centre_id, kind, period_start, period_end, season_id, tribe_id, data, generated_by)
  values (v_centre, p_kind, p_start, p_end, p_season, p_tribe,
          public.build_report(p_kind, p_start, p_end, p_season, p_tribe), p_by)
  on conflict on constraint reports_one do update
    set data = excluded.data,
        period_end = excluded.period_end,
        generated_at = now(),
        generated_by = excluded.generated_by,
        summary = case when reports.summary_by = 'edited' then reports.summary end,
        summary_by = case when reports.summary_by = 'edited' then 'edited' end
  returning id into v_id;
  return v_id;
end;
$$;

-- Who is told when a report is ready. (internal)
create function public.report_recipients(p_kind text, p_tribe uuid, p_centre uuid)
returns setof uuid
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_kind = 'tribe' then
    return query select distinct c.person_id from public.tribe_champions c
                  join public.people x on x.id = c.person_id and x.centre_id = p_centre
                 where c.tribe_id = p_tribe;
  elsif p_kind = 'pastorate' then
    if exists (select 1 from public.person_roles where role = 'pastor' and centre_id = p_centre) then
      return query select distinct r.person_id from public.person_roles r where r.role = 'pastor' and r.centre_id = p_centre;
    else
      return query select distinct r.person_id from public.person_roles r where r.role = 'director' and r.centre_id = p_centre;
    end if;
  else
    return query select distinct r.person_id from public.person_roles r where r.role in ('director', 'pastor') and r.centre_id = p_centre;
  end if;
end;
$$;

-- "Your report is ready": one message per recipient, never twice. (internal)
create function public.notify_report(p_report uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.reports%rowtype;
  v_title text;
  v_period text;
  v_to uuid;
  n integer := 0;
begin
  select * into r from public.reports where id = p_report;
  if not found then
    return 0;
  end if;
  v_title := case r.kind
               when 'programme' then 'The programme report'
               when 'pastorate' then 'The pastorate one-pager'
               when 'season' then 'The season report'
               else coalesce((select t.name from public.tribes t where t.id = r.tribe_id), 'Your tribe') || ' report' end;
  v_period := case when r.kind = 'season' then (select s.name from public.seasons s where s.id = r.season_id)
                   else to_char(r.period_start, 'FMMonth YYYY') end;
  for v_to in select * from public.report_recipients(r.kind, r.tribe_id, r.centre_id) loop
    if public.enqueue_message(v_to, 'report_ready',
         jsonb_build_object('title', v_title, 'period', v_period, 'report_id', r.id, 'kind', r.kind),
         null, 'report:' || r.id || ':' || v_to) is not null then
      n := n + 1;
    end if;
  end loop;
  return n;
end;
$$;

-- May this person read a report of this kind (and tribe)? (internal)
create function public.can_read_report(p_kind text, p_tribe uuid, p_centre uuid)
returns boolean
language sql
stable
