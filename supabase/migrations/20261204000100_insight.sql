  from public.kpi_snapshots k
  join public.seasons s on s.id = k.season_id;

-- Refresh them all (internal: the heartbeat, and bi_refresh for an admin)
create function public.bi_refresh_all()
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
begin
  refresh materialized view bi.members;
  refresh materialized view bi.circles;
  refresh materialized view bi.weekly;
  refresh materialized view bi.care_weekly;
  refresh materialized view bi.messages_daily;
  refresh materialized view bi.ai_fields;
  refresh materialized view bi.kpi_daily;
  update bi.config set refreshed_at = now();
  return (select c.refreshed_at from bi.config c);
end;
$$;

create function public.bi_refresh()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'Sign in first' using errcode = '42501';
  end if;
  if not public.has_any_role(array['admin', 'director', 'data_lead']::public.app_role[]) then
    raise exception 'Only the admin, directors and the data lead can refresh the BI copy' using errcode = '42501';
  end if;
  perform public.bi_refresh_all();
  perform public.write_event(uid, 'bi.refreshed', 'bi', 'bi', '{}'::jsonb);
  return public.bi_status();
end;
$$;

create function public.bi_status()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Sign in first' using errcode = '42501';
  end if;
  if not public.has_any_role(array['admin', 'director', 'data_lead']::public.app_role[]) then
    raise exception 'Only the admin, directors and the data lead can see the BI copy' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'refreshed_at', (select c.refreshed_at from bi.config c),
    'reader_role', 'bi_reader',
    'views', jsonb_build_array(
      jsonb_build_object('name', 'bi.members', 'rows', (select count(*) from bi.members)),
      jsonb_build_object('name', 'bi.circles', 'rows', (select count(*) from bi.circles)),
      jsonb_build_object('name', 'bi.weekly', 'rows', (select count(*) from bi.weekly)),
      jsonb_build_object('name', 'bi.care_weekly', 'rows', (select count(*) from bi.care_weekly)),
      jsonb_build_object('name', 'bi.messages_daily', 'rows', (select count(*) from bi.messages_daily)),
      jsonb_build_object('name', 'bi.ai_fields', 'rows', (select count(*) from bi.ai_fields)),
      jsonb_build_object('name', 'bi.kpi_daily', 'rows', (select count(*) from bi.kpi_daily))));
end;
$$;

