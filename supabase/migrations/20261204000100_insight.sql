-- ---------------------------------------------------------------------------
-- The heartbeat's daily jobs
--
--   a snapshot of each running season, once a day
--   in the first ten days of a month: last month's programme report, pastorate one-pager and tribe reports
--   after a season ends: its report
--   the BI copy, refreshed once a day
--
-- Safe to run as often as you like: each job checks whether it has been done.
-- ---------------------------------------------------------------------------

create function public.insight_tick(p_now timestamptz)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_today date := (p_now at time zone 'Africa/Lagos')::date;
  v_month date := date_trunc('month', (p_now at time zone 'Africa/Lagos'))::date;
  v_prev_start date;
  v_prev_end date;
  s public.seasons%rowtype;
  t record;
  k text;
  v_id uuid;
  n_snap integer := 0;
  n_reports integer := 0;
  v_bi boolean := false;
begin
  -- A snapshot for each season that is running, or ended in the last two weeks
  for s in select * from public.seasons x where x.starts_on <= v_today and x.ends_on + 14 >= v_today loop
    if not exists (select 1 from public.kpi_snapshots q where q.season_id = s.id and q.taken_on = v_today) then
      perform public.take_snapshot(s.id, p_now);
      n_snap := n_snap + 1;
    end if;
  end loop;

  -- Last month's reports, from the 1st to the 10th (the days after that are for catching up a missed tick)
  if extract(day from v_today) <= 10 then
    v_prev_end := v_month - 1;
    v_prev_start := date_trunc('month', v_prev_end)::date;
    for s in select * from public.seasons x where x.starts_on <= v_prev_end and x.ends_on >= v_prev_start loop
      continue when not exists (select 1 from public.circles c where c.season_id = s.id and c.status = 'approved');
      foreach k in array array['programme', 'pastorate'] loop
        if not exists (select 1 from public.reports r where r.kind = k and r.period_start = v_prev_start and r.season_id = s.id) then
          v_id := public.make_report(k, v_prev_start, v_prev_end, s.id, null, null);
          perform public.notify_report(v_id);
          n_reports := n_reports + 1;
        end if;
      end loop;
      for t in select distinct c.tribe_id from public.circles c
                where c.season_id = s.id and c.status = 'approved' and c.tribe_id is not null loop
        if not exists (select 1 from public.reports r where r.kind = 'tribe' and r.period_start = v_prev_start
                          and r.season_id = s.id and r.tribe_id = t.tribe_id) then
          v_id := public.make_report('tribe', v_prev_start, v_prev_end, s.id, t.tribe_id, null);
          perform public.notify_report(v_id);
          n_reports := n_reports + 1;
        end if;
      end loop;
    end loop;
  end if;

  -- A finished season's report, in the thirty days after it ends
  for s in select * from public.seasons x where x.ends_on < v_today and x.ends_on + 30 >= v_today loop
    continue when not exists (select 1 from public.circles c where c.season_id = s.id and c.status = 'approved');
    if not exists (select 1 from public.reports r where r.kind = 'season' and r.season_id = s.id) then
      v_id := public.make_report('season', s.starts_on, s.ends_on, s.id, null, null);
      perform public.notify_report(v_id);
      n_reports := n_reports + 1;
    end if;
  end loop;

  -- The BI copy, once a day
  if coalesce((select (c.refreshed_at at time zone 'Africa/Lagos')::date from bi.config c), date '1970-01-01') < v_today then
    perform public.bi_refresh_all();
    v_bi := true;
  end if;

  return jsonb_build_object('snapshots', n_snap, 'reports', n_reports, 'bi_refreshed', v_bi);
end;
$$;

-- The heartbeat: the calendar, the care sweep, then the daily jobs. A fault in the daily jobs is reported but
-- never stops a message from going out.
create or replace function public.worker_tick(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_insight jsonb;
begin
  perform public.worker_ok(p_token);
  begin
    v_insight := public.insight_tick(now());
  exception when others then
    v_insight := jsonb_build_object('insight_error', sqlerrm);
  end;
  return public.run_calendar(now()) || public.care_sweep(now()) || v_insight;
end;
$$;

-- ---------------------------------------------------------------------------
-- The tribe champion's page
--
-- A champion sees only their own tribe(s); the office can look at any. It is the same arithmetic as the church
-- dashboard, with a rate hidden for any group smaller than the minimum cell so nobody's answer can be guessed.
-- ---------------------------------------------------------------------------

create function public.tribe_dashboard(p_tribe uuid default null, p_season uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  office boolean := public.has_any_role(array['admin', 'director', 'pastor', 'data_lead']::public.app_role[]);
  v_tribe public.tribes%rowtype;
  v_mine jsonb;
  sid uuid;
  s public.seasons%rowtype;
  today date := public.today_lagos();
  tg jsonb := public.kpi_targets();
  mincell integer := (public.kpi_targets() ->> 'min_cell')::int;
  cw integer;
  gone integer;
  scope uuid[];
  core jsonb;
  v_church jsonb;
  v_supply jsonb;
begin
  if uid is null then
    raise exception 'Sign in first' using errcode = '42501';
  end if;
  if not (office or exists (select 1 from public.tribe_champions c where c.person_id = uid)) then
    raise exception 'Only tribe champions and the office can see a tribe page' using errcode = '42501';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('id', t.id, 'name', t.name) order by t.sort), '[]'::jsonb) into v_mine
    from public.tribes t
   where t.active and (office or exists (select 1 from public.tribe_champions c where c.person_id = uid and c.tribe_id = t.id));

  if p_tribe is null then
    select * into v_tribe from public.tribes t where t.id = ((v_mine -> 0) ->> 'id')::uuid;
  else
    select * into v_tribe from public.tribes t where t.id = p_tribe;
  end if;
  if not found or not (office or exists (select 1 from public.tribe_champions c where c.person_id = uid and c.tribe_id = v_tribe.id)) then
    raise exception 'We could not find that tribe' using errcode = 'P0002';
  end if;

  sid := public.dashboard_season(p_season);
  select * into s from public.seasons where id = sid;
  if not found then
    return jsonb_build_object('state', 'none', 'tribe', jsonb_build_object('id', v_tribe.id, 'name', v_tribe.name), 'tribes', v_mine);
  end if;
  cw := public.season_week(s.starts_on, s.weeks, today);
  gone := case when cw = 0 then 0 when cw > s.weeks then s.weeks else cw - 1 end;

  select coalesce(array_agg(c.id), '{}') into scope
    from public.circles c where c.season_id = sid and c.status = 'approved' and c.tribe_id = v_tribe.id;
  core := public.dashboard_core(sid, scope);

  -- Who wants this tribe, against the seats certified leaders can offer, by age group
  v_church := public.church_views(sid);
  select coalesce(jsonb_agg(
           e || jsonb_build_object('short', greatest((e ->> 'wants')::int - (e ->> 'seats')::int, 0),
                                   'circles_to_open', ceil(greatest((e ->> 'wants')::int - (e ->> 'seats')::int, 0) / 10.0)::int)
           order by e ->> 'track'), '[]'::jsonb) into v_supply
    from jsonb_array_elements(v_church -> 'supply' -> 'cells') e
   where e ->> 'tribe' = v_tribe.name;

  return jsonb_build_object(
    'state', case when cw = 0 then 'before' when cw > s.weeks then 'complete' else 'running' end,
    'tribe', jsonb_build_object('id', v_tribe.id, 'name', v_tribe.name),
    'tribes', v_mine,
    'season', jsonb_build_object('id', s.id, 'name', s.name, 'starts_on', s.starts_on, 'weeks', s.weeks,
                                 'current_week', case when cw between 1 and s.weeks then cw end, 'weeks_over', gone),
    'min_cell', mincell,
    'targets', jsonb_build_object('thriving_rate', tg -> 'thriving_rate', 'effective_thriving', tg -> 'effective_thriving',
                                  'gain_min', tg -> 'gain_min', 'min_weeks', tg -> 'min_weeks'),
    'headline', public.hide_small_headline(core -> 'headline', mincell),
    'circles', public.hide_small_cells(core -> 'circles', mincell),
    'weeks', core -> 'weeks',
    'supply', v_supply,
    'testimonies', jsonb_build_object(
      'waiting', (select count(*) from public.testimonies t join public.circles c on c.id = t.circle_id
                   where c.id = any (scope) and t.status in ('submitted', 'circle_approved')),
      'church', (select count(*) from public.testimonies t join public.circles c on c.id = t.circle_id
                  where c.id = any (scope) and t.status = 'church_approved'),
      'recent', public.report_testimonies(sid, s.starts_on, s.ends_on, v_tribe.id, 5)),
    'care', jsonb_build_object(
      'open', (select count(*) from public.care_tasks t where t.circle_id = any (scope) and t.status = 'open'),
      'late', (select count(*) from public.care_tasks t where t.circle_id = any (scope) and t.status = 'open' and t.due_on < today)),
    'champions', coalesce((select jsonb_agg(public.person_display_name(c.person_id) order by public.person_display_name(c.person_id))
                             from public.tribe_champions c where c.tribe_id = v_tribe.id), '[]'::jsonb));
end;
$$;

-- ---------------------------------------------------------------------------
-- The read-only copy for BI tools
--
-- Schema "bi": materialized views, refreshed once a day by the heartbeat (or by an admin). Every person is
-- replaced by a code that cannot be turned back into a name without the salt in bi.config, which nobody but
-- the database owner can read. There are no names, no contact details, no free text and nothing from the
-- care or support notes. Connect a BI tool as the role "bi_reader" (README: BI copy).
-- ---------------------------------------------------------------------------

create schema bi;
revoke all on schema bi from public;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'bi_reader') then
    create role bi_reader nologin;
  end if;
end;
$$;

create table bi.config (
  id boolean primary key default true check (id),
  salt text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  refreshed_at timestamptz
);
alter table bi.config enable row level security;
insert into bi.config (id) values (true);

-- One row per member in a season
create materialized view bi.members as
select s.id as season_id,
       s.name as season,
       md5(cfg.salt || k.km_person::text) as member_key,
       c.id as circle_id,
       t.name as tribe,
       tr.name as track,
       sg.title as season_goal,
       mp.zone,
       k.km_degree::int as degree_of_compatibility,
       k.km_rank::int as chosen_rank,
       k.km_attended as meetings_attended,
       k.km_recent as meetings_attended_last_3,
       k.km_belonging as belonging_latest,
       k.km_base as success_week_1,
       k.km_latest as success_latest,
       k.km_gain as success_gain,
       k.km_set as steps_set,
       k.km_done as steps_done,
       k.km_checked as steps_checked,
       k.km_thriving as thriving,
       (select (cm.joined_at at time zone 'Africa/Lagos')::date from public.circle_members cm
         where cm.person_id = k.km_person and cm.circle_id = k.km_circle order by cm.joined_at limit 1) as joined_on,
       round(mp.duration_seconds / 60.0, 1) as form_minutes,
       (select count(*) from jsonb_object_keys(case when jsonb_typeof(mp.ai_assist) = 'object' then mp.ai_assist else '{}'::jsonb end))::int as assisted_fields
  from public.seasons s
  cross join bi.config cfg
  cross join lateral public.kpi_members(s.id) k
  join public.circles c on c.id = k.km_circle
  left join public.tribes t on t.id = c.tribe_id
  left join public.tracks tr on tr.id = c.track_id
  left join public.season_goals sg on sg.id = c.season_goal_id
  left join public.member_profiles mp on mp.person_id = k.km_person;

-- One row per circle
create materialized view bi.circles as
select s.id as season_id,
       s.name as season,
       c.id as circle_id,
       t.name as tribe,
       tr.name as track,
       sg.title as season_goal,
       c.capacity,
       k.kc_members as members,
       k.kc_held as meetings_held,
       k.kc_present as present,
       k.kc_possible as possible,
       case when k.kc_possible > 0 then round(k.kc_present::numeric / k.kc_possible, 3) end as attendance_rate,
       k.kc_thriving as thriving,
       case when k.kc_measured and k.kc_members > 0 then round(k.kc_thriving::numeric / k.kc_members, 3) end as thriving_rate,
       k.kc_gain_n as gain_answers,
       case when k.kc_gain_n > 0 then round(k.kc_gain_avg, 2) end as gain_avg,
       k.kc_verdict as verdict,
       c.coach_id is not null as has_coach,
       exists (select 1 from public.leader_certifications lc where lc.person_id = c.leader_id) as leader_certified,
       exists (select 1 from public.leader_certifications lc where lc.person_id = c.assistant_id and lc.as_role = 'assistant_leader') as assistant_certified
  from public.seasons s
  cross join lateral public.kpi_circles(s.id) k
  join public.circles c on c.id = k.kc_circle
  left join public.tribes t on t.id = c.tribe_id
  left join public.tracks tr on tr.id = c.track_id
  left join public.season_goals sg on sg.id = c.season_goal_id;

-- One row per circle per week
create materialized view bi.weekly as
select s.id as season_id,
       s.name as season,
       l.circle_id,
       l.week::int as week,
       public.meeting_date_of(l.circle_id, l.week) as meeting_date,
       l.held,
       count(a.person_id) filter (where a.status = 'present')::int as present,
       count(a.person_id)::int as marked,
       (select count(*) from public.week_steps ws where ws.circle_id = l.circle_id and ws.week = l.week)::int as steps_set,
       (select count(*) from public.week_steps ws where ws.circle_id = l.circle_id and ws.week = l.week and ws.outcome = 'done')::int as steps_done
  from public.circle_logs l
  join public.circles c on c.id = l.circle_id
  join public.seasons s on s.id = c.season_id
  left join public.circle_attendance a on a.circle_id = l.circle_id and a.week = l.week
 group by s.id, s.name, l.circle_id, l.week, l.held;

-- Care tasks by week and kind: how many were raised and how many closed (no names, no notes)
create materialized view bi.care_weekly as
select x.week_start, x.kind, sum(x.opened)::int as opened, sum(x.closed)::int as closed
  from (
    select date_trunc('week', (t.created_at at time zone 'Africa/Lagos'))::date as week_start, t.kind, 1 as opened, 0 as closed
      from public.care_tasks t
    union all
    select date_trunc('week', (t.closed_at at time zone 'Africa/Lagos'))::date, t.kind, 0, 1
      from public.care_tasks t where t.status = 'done' and t.closed_at is not null) x
 group by x.week_start, x.kind;

-- Messages by day, template, channel and outcome (no recipients, no text)
create materialized view bi.messages_daily as
select (m.created_at at time zone 'Africa/Lagos')::date as day,
       m.template,
       coalesce(m.channel, 'none') as channel,
       m.status,
       count(*)::int as messages
  from public.messages m
 group by 1, 2, 3, 4;

-- How often each suggestion of the assistant is kept, by field and season
create materialized view bi.ai_fields as
select s.id as season_id,
       s.name as season,
       f ->> 'field' as field,
       (f ->> 'shown')::int as shown,
       (f ->> 'kept')::int as kept,
       (f ->> 'rate')::numeric as keep_rate
  from public.seasons s
  cross join lateral jsonb_array_elements(coalesce(public.insight_data(s.id) -> 'ai' -> 'fields', '[]'::jsonb)) f;

-- The daily snapshots, one row per season per day
