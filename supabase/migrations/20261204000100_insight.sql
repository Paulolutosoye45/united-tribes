-- ---------------------------------------------------------------------------
-- The retention curve
--
-- Cohort: everyone placed in a circle for the season (anyone released before it began is left out).
-- At week w a member is "still coming" when they were present at a held meeting in week w or w-1, so one
-- missed week does not count as leaving. Only weeks that are over are drawn.
-- ---------------------------------------------------------------------------

create function public.retention_curve(p_season uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  s public.seasons%rowtype;
  cw integer;
  gone integer;
  cohort integer;
begin
  select * into s from public.seasons where id = p_season;
  if not found then
    return jsonb_build_object('cohort', 0, 'points', '[]'::jsonb);
  end if;
  cw := public.season_week(s.starts_on, s.weeks, public.today_lagos());
  gone := case when cw = 0 then 0 when cw > s.weeks then s.weeks else cw - 1 end;
  -- a member who moved to another circle counts once
  select count(distinct m.person_id)::int into cohort
    from public.circle_members m
    join public.circles c on c.id = m.circle_id
   where m.season_id = p_season and c.status = 'approved'
     and (m.status = 'active' or m.released_at >= s.starts_on);
  return jsonb_build_object(
    'cohort', cohort,
    'points', coalesce((
      select jsonb_agg(jsonb_build_object(
               'week', g.w, 'retained', r.n,
               'rate', case when cohort > 0 then round(r.n::numeric / cohort, 3) end) order by g.w)
        from generate_series(1, gone) as g(w)
        cross join lateral (
          select count(distinct a.person_id)::int as n
            from public.circle_attendance a
            join public.circle_logs l on l.circle_id = a.circle_id and l.week = a.week and l.held
            join public.circle_members m on m.circle_id = a.circle_id and m.person_id = a.person_id and m.season_id = p_season
           where a.status = 'present' and a.week between greatest(1, g.w - 1) and g.w) r), '[]'::jsonb));
end;
$$;

-- "met" / "close" / "behind" / "na": one rule for every KPI. dir 'min' means higher is better, 'max' lower is better.
create function public.kpi_status(p_value numeric, p_target numeric, p_dir text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when p_value is null or p_target is null then 'na'
    when p_dir = 'max' then case when p_value <= p_target then 'met' when p_value <= p_target * 1.3 then 'close' else 'behind' end
    else case when p_value >= p_target then 'met' when p_value >= p_target * 0.9 then 'close' else 'behind' end
  end;
$$;

-- One KPI as the dashboard draws it.
create function public.kpi_row(
  p_key text, p_objective text, p_value numeric, p_target numeric, p_dir text, p_n integer, p_unit text,
