-- Makes a report now (the heartbeat makes them on its own each month). month is any date in the month wanted.
create function public.generate_report(
  p_kind text,
  p_month date default null,
  p_tribe uuid default null,
  p_season uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  v_today date := public.today_lagos();
  v_start date;
  v_end date;
  v_season uuid := p_season;
  s public.seasons%rowtype;
  v_id uuid;
begin
  if uid is null then
    raise exception 'Sign in first' using errcode = '42501';
  end if;
  if not public.has_any_role(array['admin', 'director', 'pastor', 'data_lead']::public.app_role[]) then
    raise exception 'Only the pastorate, directors and the data lead can make a report' using errcode = '42501';
  end if;
  if p_kind not in ('programme', 'pastorate', 'tribe', 'season') then
    raise exception 'Choose programme, pastorate, tribe or season' using errcode = '22023';
  end if;
  if p_kind = 'tribe' and p_tribe is null then
    raise exception 'Choose a tribe' using errcode = '22023';
  end if;
  if p_kind <> 'tribe' and p_tribe is not null then
    raise exception 'Only a tribe report has a tribe' using errcode = '22023';
  end if;

  if p_kind = 'season' then
    v_season := public.dashboard_season(p_season);
    select * into s from public.seasons where id = v_season;
    if not found then
      raise exception 'There is no season yet' using errcode = 'P0002';
    end if;
    v_start := s.starts_on;
    v_end := s.ends_on;
  else
    v_start := date_trunc('month', coalesce(p_month, (v_today - interval '1 month')::date))::date;
    v_end := (v_start + interval '1 month')::date - 1;
    if v_start > v_today then
      raise exception 'That month has not begun' using errcode = '22023';
    end if;
    if v_season is null then
      select x.id into v_season from public.seasons x
       where x.starts_on <= v_end and x.ends_on >= v_start and x.centre_id = public.my_centre()
       order by x.starts_on desc limit 1;
      if v_season is null then
        v_season := public.dashboard_season(null);
      end if;
    else
      v_season := public.dashboard_season(v_season);
    end if;
    if v_season is null then
      raise exception 'There is no season yet' using errcode = 'P0002';
    end if;
  end if;

  v_id := public.make_report(p_kind, v_start, v_end, v_season, p_tribe, uid);
  perform public.write_event(uid, 'report.generated', 'report', v_id::text, jsonb_build_object('kind', p_kind, 'month', v_start));
  return public.get_report(v_id);
end;
$$;

