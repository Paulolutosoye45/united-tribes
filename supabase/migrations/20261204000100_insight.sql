-- Stage 5: insight
--
-- What the office, the pastorate and tribe champions need to run the programme without a spreadsheet.
--
--   kpi_settings / kpi_targets()   the numbers the programme is held to, now editable (set_kpi_target)
--   word_habit                     "how many days did you open the Word this week?" (member, weekly)
--   tribe_champions                who champions which tribe; tribe_dashboard() is their view
--   retention_curve(season)        the share of a season's members still coming, week by week
--   insight(season)                the nine objectives with their targets, the AI keep rate by field,
--                                  Success Picture progress by goal, and the trend from daily snapshots
--   kpi_snapshots                  one row per season per day, so history is never lost
--   reports                        the monthly programme report, the pastorate one-pager, the tribe
--                                  reports and the season report, generated by the heartbeat
--   bi.*                           a read-only copy for BI tools, with every person replaced by a code
--
-- Every figure is still worked out from the same rows as the dashboard (kpi_members / kpi_circles), so a
-- number in a report can never disagree with the number on the dashboard.
--
-- Deviations from the blueprint, on purpose:
--   * Ratings are 1 to 5 on three lines (God, others, life), added to 3-15, not 1 to 10 on one line.
--     A "gain of 2" is therefore 2 points of 15. The README explains why (phone-friendly, less hair-splitting).
--   * "Weekly Word habit" is reported by the member each week (0 to 7 days); a member keeps the habit when
--     their last three reports average at least four days.
--   * "Intake" means the day the form was submitted; "first meeting" is the first held meeting they attended.

-- ---------------------------------------------------------------------------
-- The targets, now editable
-- ---------------------------------------------------------------------------

create table public.kpi_settings (
  key text primary key check (key ~ '^[a-z_]{2,40}$'),
  value numeric not null,
  updated_by uuid references public.people (id) on delete set null,
  updated_at timestamptz not null default now()
);
alter table public.kpi_settings enable row level security;
-- No grants: only the functions touch this table.

-- The one list of targets, their sensible bounds, and whether they must be whole numbers.
create function public.kpi_target_defs()
returns table (d_key text, d_default numeric, d_lo numeric, d_hi numeric, d_whole boolean)
language sql
immutable
set search_path = ''
as $$
  select * from (values
    ('thriving_rate',       0.85::numeric, 0.5::numeric, 1::numeric, false),   -- share of members thriving
    ('attend_share',        2.0 / 3,       0.3,          1,          false),   -- 8 of 12 meetings
    ('belonging_min',       4,             1,            5,          true),
    ('gain_min',            2,             1,            12,         true),    -- points on the 3 to 15 Success Picture score
    ('effective_thriving',  0.80,          0.5,          1,          false),
    ('effective_gain',      0.70,          0.3,          1,          false),
    ('min_weeks',           3,             1,            12,         true),    -- no rate before this many weeks
    ('min_cell',            5,             2,            50,         true),    -- breakdowns hide a rate for fewer people
    ('min_answers',         3,             2,            50,         true),    -- an average needs this many answers
    ('retrain_after',       300,           50,           5000,       true),    -- placements before the weights are retrained
    ('connect_days',        14,            1,            60,         true),    -- median days intake to first meeting (launch)
    ('connect_days_season', 7,             1,            60,         true),    -- ... once the programme is established
    ('form_minutes',        6,             1,            60,         true),    -- median minutes on the form
    ('form_completion',     0.85,          0.3,          1,          false),   -- started forms that were finished
    ('ai_keep',             0.70,          0.3,          1,          false),   -- suggestions kept, for every field
    ('word_habit',          0.70,          0.3,          1,          false),   -- members keeping the weekly Word habit
    ('word_days_min',       4,             1,            7,          true),    -- days a week that counts as keeping it
    ('care_resolved',       0.95,          0.3,          1,          false),   -- care tasks resolved within the days below
    ('care_days',           7,             1,            30,         true),
    ('assistants',          1.0,           0,            5,          false),   -- certified assistants per circle
    ('match_gap',           0.05,          0,            0.5,        false),   -- thriving gap, 85%+ matches over 60-69%
    ('swap_weeks',          4,             1,            12,         true)     -- a member may ask to change circle in the first weeks
  ) as v (d_key, d_default, d_lo, d_hi, d_whole);
$$;

create or replace function public.kpi_targets()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_object_agg(d.d_key, coalesce(k.value, d.d_default))
    from public.kpi_target_defs() d
    left join public.kpi_settings k on k.key = d.d_key;
$$;

-- Office and directors change a target; the old value is kept in the audit log.
create function public.set_kpi_target(p_key text, p_value numeric)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  d record;
  v numeric;
  before numeric;
begin
  if uid is null then
    raise exception 'Sign in first' using errcode = '42501';
  end if;
  if not public.has_any_role(array['admin', 'director', 'data_lead']::public.app_role[]) then
    raise exception 'Only the admin, directors and the data lead can change a target' using errcode = '42501';
  end if;
  select * into d from public.kpi_target_defs() x where x.d_key = p_key;
  if not found then
    raise exception 'That is not a target we measure' using errcode = '22023';
  end if;
  if p_value is null or p_value < d.d_lo or p_value > d.d_hi then
    raise exception 'Choose a number from % to %', d.d_lo, d.d_hi using errcode = '22023';
  end if;
  v := case when d.d_whole then round(p_value) else round(p_value, 4) end;
  select coalesce(k.value, d.d_default) into before from (select 1) o left join public.kpi_settings k on k.key = p_key;
  insert into public.kpi_settings (key, value, updated_by, updated_at) values (p_key, v, uid, now())
  on conflict (key) do update set value = excluded.value, updated_by = excluded.updated_by, updated_at = now();
  perform public.write_event(uid, 'kpi.target_set', 'kpi', p_key, jsonb_build_object('from', before, 'to', v));
  return public.kpi_target_list();
end;
$$;

